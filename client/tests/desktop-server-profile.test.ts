import assert from "node:assert/strict";
import { registerServiceWorker } from "../serviceWorkerRegistration";
import { getCacheBaseUrl, getCacheListUrl, getDefaultWsUrl } from "../config/clientEnv";
import { LoginState } from "../game/login/LoginState";
import { setServerUrl } from "../network/serverConnection/outgoing/connectionInfo";
import { state } from "../network/serverConnection/state";
import { updateClientPreferences } from "../game/preferences/ClientPreferences";

(globalThis as any).window = { location: { hostname: "localhost", pathname: "/", search: "" } };
window.__RSPS_DESKTOP_PROFILE__ = { name: "TobiasScape", address: "localhost:43715", secure: false, maxPlayers: 2047 };
updateClientPreferences({ lastServer: undefined });
delete process.env.REACT_APP_CACHE_BASE_URL;
process.env.PUBLIC_URL = "/";
assert.equal(getCacheBaseUrl(), "https://rsps.app/play/caches/");
assert.equal(getCacheListUrl(), "/caches/caches.json", "desktop cache selection comes from its installed release");
process.env.REACT_APP_CACHE_BASE_URL = "https://cdn.example.com/caches";
assert.equal(getCacheBaseUrl(), "https://cdn.example.com/caches/");
assert.equal(getCacheListUrl(), "/caches/caches.json", "a CDN must not replace the release's pinned cache selection");
delete process.env.REACT_APP_CACHE_BASE_URL;
const initial = new LoginState();
assert.equal(initial.serverName, "TobiasScape");
assert.equal(initial.serverAddress, "localhost:43715");
assert.equal(getDefaultWsUrl(), "ws://localhost:43715");
initial.serverName = "Other world";
assert.equal(initial.serverName, "Other world", "desktop titles follow the selected world like the browser");
setServerUrl("wss://other.example/game", null);
assert.equal(state.lastUrl, "wss://other.example/game", "desktop profiles do not override selected worlds");
updateClientPreferences({ lastServer: { name: "Other", address: "other.example", secure: true, transport: "webrtc", signalUrl: "wss://relay.example", worldId: "solaris", iceServers: [] } });
const restored = new LoginState();
assert.equal(restored.serverAddress, "localhost:43715", "desktop starts on its configured world despite a saved choice");
assert.equal(restored.serverName, "TobiasScape");
assert.equal(restored.serverTransport, "websocket");
assert.equal(restored.serverSignalUrl, undefined, "saved WebRTC settings cannot leak into the configured starting world");
let workerRegistrations = 0;
(globalThis as any).window.addEventListener = () => workerRegistrations++;
Object.defineProperty(globalThis, "navigator", { configurable: true, value: { serviceWorker: {} } });
process.env.NODE_ENV = "production";
registerServiceWorker();
assert.equal(workerRegistrations, 0, "browser workers must not serve stale assets over native updates");
window.__RSPS_DESKTOP_PROFILE__ = { name: "Hosted world", address: "worlds.rsps.app", secure: true, maxPlayers: 2047,
    transport: "webrtc", signalUrl: "wss://worlds.rsps.app", worldId: "browser-example", iceServers: [{ urls: "stun:stun.rsps.app:3478" }] };
const hosted = new LoginState();
assert.equal(hosted.serverTransport, "webrtc");
assert.equal(hosted.serverWorldId, "browser-example");
assert.equal(hosted.serverSignalUrl, "wss://worlds.rsps.app");
assert.equal(hosted.serverAddress, "worlds.rsps.app");
delete window.__RSPS_DESKTOP_PROFILE__;
assert.equal(getCacheBaseUrl(), "/caches/");
assert.equal(getCacheListUrl(), "/caches/caches.json", "browser cache selection stays unchanged");
process.env.REACT_APP_CACHE_BASE_URL = "https://cdn.example.com/caches/";
assert.equal(getCacheListUrl(), "https://cdn.example.com/caches/caches.json", "browser overrides keep their existing behaviour");
delete process.env.REACT_APP_CACHE_BASE_URL;
assert.equal(new LoginState().serverAddress, "other.example", "browser clients still restore saved worlds");
registerServiceWorker();
assert.equal(workerRegistrations, 1, "the browser PWA still registers its worker");
console.log("Desktop starts on its configured world, permits switching, and leaves browser world restoration unchanged.");
