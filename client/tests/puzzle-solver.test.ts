// The server scrambles boxes with 101 random slides; a few of those take IDA* minutes. Past its
// budget the solve falls back to the row-by-row solver, which still ends solved.
{
    const hard = [5, 0, 4, 2, 9, 10, 7, 3, 19, 8, 6, 1, 18, -1, 14, 15, 11, 16, 12, 13, 20, 21, 17, 22, 23];
    const steps = computeSteps(hard, false, 0);
    assert.ok(steps !== null, "an exhausted budget still gives a solution");
    assert.deepEqual(steps[0], hard);
    assert.deepEqual(steps[steps.length - 1], FINISHED_STATE);
    assert.equal(computeSteps([0, 1, 2], false), null, "a malformed board fails instead of throwing");
    assert.equal(computeSteps([...FINISHED_STATE.slice(0, 24), 30], false, 0), null, "a board without a blank fails");
    console.log(`Budget fallback: ${steps.length - 1} slides`);
}
