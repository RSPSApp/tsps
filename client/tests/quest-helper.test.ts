import { strict as assert } from "node:assert";
import { parseHelperResponse, parseHelperCatalog } from "../game/plugins/questhelper/QuestHelperProtocol";
import { QuestHelperSession } from "../game/plugins/questhelper/QuestHelperSession";
import { OwnedTileHighlights, resolveTargetTiles } from "../game/plugins/questhelper/QuestHelperHighlights";
import { TileHighlightManager } from "../game/highlights/TileHighlightManager";
const snapshot: any = {varps:{},varbits:{},inventory:[],equipment:[],localPlayer:{name:'A',x:3200,y:3200,plane:0},skills:{},npcs:[{index:1,id:10,transformedId:11,name:'Guide',x:3201,y:3202,plane:0}],objects:[],groundItems:[],widgets:[],baseX:3150,baseY:3150,plane:0,tick:1};
const response = (session:string,sequence:number,questKey='cooks_assistant'):any => ({protocol:1,session,sequence,questKey,sourceCommit:'abc',status:'active',activeStep:{id:'talk',text:['Talk to the cook.'],targets:[{kind:'npc',id:11}],requirements:[{name:'Egg',met:false,ids:[1944],quantity:1}],dialogueChoices:[],widgets:[],overlays:[]},panels:[],diagnostics:[]});
assert.equal(parseHelperResponse({...response('s',1),activeStep:{text:['oops']}}),null);
assert.equal(parseHelperResponse({...response('s',1),sequence:NaN}),null);
assert.equal(parseHelperResponse({...response('s',1),activeStep:{...response('s',1).activeStep,targets:[{kind:'code',id:1}]}}),null);
assert.equal(parseHelperResponse(response('s',1))?.activeStep?.requirements[0].met,false);
assert.equal(parseHelperCatalog({protocol:1,sourceCommit:'abc',quests:[{questKey:'cook',name:'Cook',supported:true}],diagnostics:[]})?.quests.length,1);
const requests:any[]=[]; let generation=0;
const helper=new QuestHelperSession(data=>requests.push(data),()=>`s${++generation}`);
helper.select('cooks_assistant'); helper.update('A',snapshot);
const first=requests.find(x=>x.type==='evaluate'); assert.ok(first);
assert.ok(helper.accept(response(first.session,first.sequence)));
helper.update('A',{...snapshot,tick:2}); const second=requests.filter(x=>x.type==='evaluate').at(-1);
assert.equal(helper.accept(response(first.session,first.sequence)),false,'old sequence must not restore old markers');
assert.ok(helper.accept(response(second.session,second.sequence)));
helper.select('sheep_shearer'); assert.equal(helper.getState().result,null);
assert.equal(helper.accept(response(second.session,second.sequence)),false);
helper.update('B',snapshot); assert.equal(helper.getState().result,null);
assert.equal(helper.accept(response(second.session,second.sequence)),false,'account switches invalidate sessions');
helper.close(); assert.equal(helper.getState().result,null);
assert.equal(helper.accept(response(second.session,second.sequence)),false);
assert.deepEqual(resolveTargetTiles([{kind:'npc',id:11}],snapshot,0),[{x:3201,y:3202,plane:0}]);
assert.deepEqual(resolveTargetTiles([{kind:'npc',id:10}],snapshot,0),[],'transformed definitions control identity');
assert.deepEqual(resolveTargetTiles([{kind:'tile',x:3201,y:3202,plane:1}],snapshot,0),[]);
const tiles=new TileHighlightManager(); const owned=new OwnedTileHighlights(tiles,60001);
tiles.configure(7,0xff0000,1,20,0); tiles.set((3200<<14)|3200,7,0);
owned.replace([{x:3201,y:3202,plane:0}],0x00ff00); assert.equal(tiles.getRenderEntries().length,2);
owned.clear(); assert.equal(tiles.getRenderEntries().length,1,'only helper-owned slots are cleared');
console.log('quest helper protocol, isolation and highlights passed');
