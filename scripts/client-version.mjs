import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));

export function clientVersion(repositoryRoot = root) {
    // The release workflow is the single list of inputs that can change the client.
    const workflow = readFileSync(resolve(repositoryRoot, ".github/workflows/client-release.yml"), "utf8").replace(/\r\n/g, "\n");
    const push = workflow.split("    push:\n")[1]?.split("    pull_request:")[0];
    if (!push) throw new Error("Missing client release inputs");
    const paths = [...push.matchAll(/^            - '([^']+)'$/gm)].map(match => match[1]);
    if (!paths.length) throw new Error("Missing client release paths");
    const files = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z", "--", ...paths], { cwd: repositoryRoot, encoding: "utf8" });
    const hash = createHash("sha256");
    for (const path of [...new Set(files.split("\0").filter(Boolean))].sort()) {
        let bytes = readFileSync(resolve(repositoryRoot, path));
        // Text checkout line endings must not give Windows worlds a different client build.
        if (/\.(?:[cm]?[jt]sx?|json|ya?ml|txt|md|css|scss|html|svg|xml|toml|lock)$/.test(path)) {
            bytes = Buffer.from(bytes.toString("utf8").replace(/\r\n/g, "\n"));
        }
        hash.update(path + "\0" + bytes.length + "\0").update(bytes);
    }
    return hash.digest("hex");
}

export function writeClientVersion() {
    const version = clientVersion();
    const output = resolve(root, "server/src/main/typescript/elvarg/ClientVersion.generated.ts");
    mkdirSync(dirname(output), { recursive: true });
    const source = `// Generated by scripts/client-version.mjs.\nexport const CLIENT_VERSION = ${JSON.stringify(version)};\n`;
    let previous;
    try { previous = readFileSync(output, "utf8"); } catch {}
    if (source !== previous) writeFileSync(output, source);
    return version;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) console.log(writeClientVersion());
