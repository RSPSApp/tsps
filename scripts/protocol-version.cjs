const { createHash } = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

// Both builds fingerprint the canonical wire code, including field changes with unchanged sizes.
const directory = path.join(__dirname, "../server/src/main/typescript/elvarg/net");
function getProtocolVersion() {
    const hash = createHash("sha256");
    const files = fs.readdirSync(path.join(directory, "protocol"))
        .filter(file => file.endsWith(".ts") && file !== "ProtocolVersion.ts").sort()
        .map(file => `protocol/${file}`);
    files.push("packet/PacketSender.ts", "packet/PacketBuilder.ts");
    for (const file of files) {
        hash.update(file).update("\0").update(fs.readFileSync(path.join(directory, file), "utf8").replace(/\r\n/g, "\n")).update("\0");
    }
    return hash.digest("hex");
}
module.exports = { getProtocolVersion };
if (require.main === module) {
    const output = path.join(__dirname, "../server/src/main/typescript/elvarg/net/protocol/ProtocolVersion.ts");
    const contents = `// Generated by scripts/protocol-version.cjs before server builds.\nexport const GAME_PROTOCOL_VERSION = ${JSON.stringify(getProtocolVersion())};\n`;
    if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== contents) fs.writeFileSync(output, contents);
}
