"use strict";
/**
 * Dresses a spawned normal boss as its Echo form. Every Echo encounter spawns the normal boss
 * NPC, with its normal actions, animations, combat definition and controller, and changes only
 * that one instance:
 *
 * - Appearance, name and level: the official `league_6_*` definitions in the cache are the
 *   normal bosses with their models swapped (same size, scale and animations; no Attack action,
 *   levels or hitpoints), so they cannot be the NPC a player attacks. Live's cache during
 *   Leagues VI (OpenRS2 2528) holds the same bytes. Live adds the normal boss and sends the
 *   stub's models as its body customisation, with a name and level change (rsprox.net
 *   1158/1161: Echo Hunllef is 9035 with model 60373, "Corrupted Hunllef (Echo)", level 1,117;
 *   docs/echo-bosses.md). The same goes out here as the NPC's type customisation.
 * - Combat values: the Wiki Echo profile (npc-encounter-variants.json, generated by
 *   osrsreboxed-db `scripts/monsters/encounter_variants.py`) through the per-instance
 *   overrides other bosses use: setMaxHitpoints and setCombatOverride (stats, max hit,
 *   attack speed). A value the profile omits keeps the normal boss's. Status immunities and
 *   weaknesses stay the normal boss's: no per-instance override exists for them.
 */
const variants = require("../../../data/definitions/npc-encounter-variants.json");

/**
 * Every role an Echo adapter configures. `normal` is the gameval of the normal form the role's
 * appearance replaces; `echo` the official Echo stub whose models it wears. KBD and Amoxliatl
 * have no stub: `echoRow` names their `leagues_echo_bosses` row, whose struct holds the single
 * Echo model the League Areas panel draws. `profile` names the Wiki profile when it differs
 * from `role`: the Wiki gives Dusk one Echo profile (its phase-4 form's).
 */
const ROLES = [
  { boss: "amoxliatl", role: "boss", normal: "amoxliatl", echo: null, echoRow: "leagues_echo_amoxliatl" },
  { boss: "cerberus", role: "boss", normal: "cerberus_attacking", echo: "league_6_cerberus" },
  { boss: "corrupted-hunllef", role: "boss", normal: "crystal_hunllef_melee_hm", echo: "league_6_crystal_hunllef_melee" },
  { boss: "dagannoth-kings", role: "rex", normal: "dagcave_melee_boss", echo: "league_6_dagcave_melee_boss" },
  { boss: "dagannoth-kings", role: "prime", normal: "dagcave_magic_boss", echo: "league_6_dagcave_magic_boss" },
  { boss: "dagannoth-kings", role: "supreme", normal: "dagcave_ranged_boss", echo: "league_6_dagcave_ranged_boss" },
  { boss: "grotesque-guardians", role: "dawn", normal: "gargboss_dawn_phase1", echo: "league_6_gg_dawn_alive" },
  { boss: "grotesque-guardians", role: "dusk", normal: "gargboss_dusk_phase2_attacking", echo: "league_6_gg_dusk_alive" },
  // Phase 4 is a size-6 form with its own rig; the only Echo Dusk is size 4.
  { boss: "grotesque-guardians", role: "dusk-final", normal: "gargboss_dusk_phase4", echo: null, profile: "dusk" },
  { boss: "hespori", role: "boss", normal: "hespori", echo: "league_6_hespori" },
  { boss: "kalphite-queen", role: "ground", normal: "kalphite_queen", echo: "league_6_kalphite_queen" },
  { boss: "kalphite-queen", role: "air", normal: "kalphite_flyingqueen", echo: "league_6_kalphite_flyingqueen" },
  { boss: "king-black-dragon", role: "boss", normal: "king_dragon", echo: null, echoRow: "leagues_echo_kbd" },
  // Live's capitalisation (rsprox.net 1161), not the cache name's.
  { boss: "thermonuclear-smoke-devil", role: "boss", normal: "smoke_devil_boss", echo: "league_6_smoke_devil_boss",
    name: "Thermonuclear Smoke Devil (Echo)" },
].map((entry) => Object.freeze({ ...entry, profile: entry.profile ?? entry.role }));
/**
 * leagues_echo_bosses' struct column and the struct param holding the Leagues VI Echo model
 * (param 1322 is the normal one). Client script 7644 (league_area_details_draw_boss) draws them.
 */
const ECHO_TABLE = "leagues_echo_bosses";
const ECHO_STRUCT_COLUMN = "ca_data";
const ECHO_MODEL_PARAM = 1999;
/** monsters-complete stat slots, as NpcDefinitionLoader fills them. */
const STAT_SLOTS = [[0, "attack_level"], [1, "strength_level"], [2, "defence_level"], [3, "ranged_level"],
  [4, "magic_level"], [5, "attack_bonus"], [7, "attack_magic"], [9, "attack_ranged"], [10, "defence_stab"],
  [11, "defence_slash"], [12, "defence_crush"], [13, "defence_magic"], [14, "defence_ranged_standard"]];

let api = null;
let resolved = null;

function roleOf(boss, role) {
  return ROLES.find((entry) => entry.boss === boss && entry.role === role) ?? null;
}

function profileOf(entry) {
  const profile = variants.bosses?.[entry.boss]?.profiles?.[entry.profile];
  if (!profile || !Number.isSafeInteger(profile.hitpoints) || profile.hitpoints < 1) {
    throw new Error(`Echo bosses: no usable ${entry.boss} ${entry.profile} profile`);
  }
  return profile;
}

/**
 * What the role shows in place of the normal form (NPC.setTypeCustomisation), as live sends it
 * (rsprox.net 1158/1161): the Echo stub's whole model list and recolours (the normal form's are
 * dropped), the Echo name and the Wiki Echo combat level.
 */
function typeCustomisation(entry, normal, echo, profile, rowModel) {
  const custom = { name: entry.name ?? `${normal.name} (Echo)` };
  if (Number.isSafeInteger(profile.combat_level)) custom.combatLevel = profile.combat_level;
  if (echo?.modelIds?.length) {
    custom.models = [...echo.modelIds];
    custom.recolours = (echo.recolorFrom ?? []).map((from, index) => ({ from, to: echo.recolorTo[index] }));
  } else if (Number.isInteger(rowModel)) {
    custom.models = [rowModel];
    custom.recolours = [];
  }
  return custom;
}

/** The Echo model of a `leagues_echo_bosses` row (its struct's ECHO_MODEL_PARAM); throws on a gap. */
function rowModelOf(rowName) {
  const { CacheDefinitions } = api.core;
  const table = CacheDefinitions.getDbTableId(ECHO_TABLE), row = CacheDefinitions.getDbRowId(rowName);
  const column = Number.isInteger(table) ? CacheDefinitions.getDbColumn(table, ECHO_STRUCT_COLUMN) : null;
  const columns = Number.isInteger(row) ? CacheDefinitions.getDbRow(row)?.columns : null;
  const struct = Number.isInteger(column) ? (columns?.get?.(column) ?? columns?.[column])?.[0] : undefined;
  const model = Number.isInteger(struct) ? CacheDefinitions.getStructParams(struct).get(ECHO_MODEL_PARAM) : undefined;
  if (!Number.isInteger(model)) throw new Error(`Echo bosses: no Echo model in ${ECHO_TABLE} row ${rowName}`);
  return model;
}

/** Resolves every role against the current cache once; throws naming the first gap. */
function resolve() {
  if (resolved) return resolved;
  const { CacheDefinitions } = api.core;
  const id = (symbol) => {
    const value = CacheDefinitions.getNpcId(symbol);
    if (!Number.isInteger(value)) throw new Error(`Echo bosses: missing cache NPC ${symbol}`);
    return value;
  };
  resolved = new Map(ROLES.map((entry) => {
    const normalId = id(entry.normal), echoId = entry.echo ? id(entry.echo) : null, profileData = profileOf(entry);
    const rowModel = entry.echoRow ? rowModelOf(entry.echoRow) : undefined;
    const custom = typeCustomisation(entry, CacheDefinitions.getNpc(normalId), echoId === null ? null : CacheDefinitions.getNpc(echoId), profileData, rowModel);
    return [`${entry.boss}:${entry.role}`, { ...entry, normalId, custom, profileData }];
  }));
  return resolved;
}

/** The normal stats with the profile's levels and bonuses; NpcDefinitionLoader's slot layout. */
function stats(normal, profile) {
  const values = [...normal];
  for (const [slot, key] of STAT_SLOTS) if (Number.isFinite(profile[key])) values[slot] = Math.trunc(profile[key]);
  return values;
}

/**
 * Applies the Echo form of `role` to a spawned normal boss. `fresh` sets its hitpoints to the
 * Echo maximum; a later call for a form change keeps the damage already dealt. Answers the
 * profile's labelled max hits (the Wiki's per-attack maxima) for controllers that cap by attack,
 * or null when the role is unknown.
 */
function dress(npc, boss, role, fresh) {
  const entry = resolve().get(`${boss}:${role}`);
  if (!entry || !npc) return null;
  const profile = entry.profileData;
  const override = { stats: stats(api.core.NpcDefinition.forId(entry.normalId).getStats(), profile) };
  if (Number.isSafeInteger(profile.max_hit) && profile.max_hit >= 0) override.maxHit = profile.max_hit;
  if (Number.isSafeInteger(profile.attack_speed) && profile.attack_speed > 0) override.attackSpeed = profile.attack_speed;
  npc.setCombatOverride(override);
  npc.setMaxHitpoints(profile.hitpoints);
  if (fresh) npc.setHitpoints(profile.hitpoints);
  npc.setTypeCustomisation(entry.custom);
  return { maxHits: (profile.max_hits ?? []).filter((row) => row.label && Number.isSafeInteger(row.max_hit))
    .map((row) => ({ label: row.label, maxHit: row.max_hit })) };
}

/** Startup check: a missing gameval or profile fails loudly at boot, not mid-encounter. */
function check() {
  try {
    resolve();
  } catch (error) {
    resolved = null;
    api.log(`Echo bosses unavailable: ${error.message}`);
  }
}

function attach(pluginApi) {
  api = pluginApi;
  resolved = null;
  api.onServerStartup(check);
}

module.exports = { attach, dress, roleOf, typeCustomisation, ROLES };
