// Keep the server and browser framing protocol byte-for-byte equivalent.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = path.resolve(__dirname, '../../client/common/network/ChunkedPluginMessages.ts');
const destination = path.resolve(__dirname, '../plugins/quests/questhelper/Chunks.QuestHelper.js');
const output = ts.transpileModule(fs.readFileSync(source, 'utf8'), {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS },
}).outputText;
fs.mkdirSync(path.dirname(destination), { recursive: true });
fs.writeFileSync(destination, '// Generated by server/scripts/build-plugin-chunks.cjs; edit client/common/network/ChunkedPluginMessages.ts.\n' + output);
