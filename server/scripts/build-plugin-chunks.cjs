// Keep the server and browser framing protocol byte-for-byte equivalent.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = path.resolve(__dirname, '../../client/common/network/ChunkedPluginMessages.ts');
const destination = path.resolve(__dirname, '../plugins/quests/questhelper/Chunks.QuestHelper.js');
function compile(sourceText) { return ts.transpileModule(sourceText, {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS },
}).outputText.replace('const pako = require("pako");', `const zlib = require('node:zlib');\nconst pako = {deflate:zlib.deflateSync,Inflate:class {push(bytes){this.onData(zlib.inflateSync(bytes,{maxOutputLength:4*1024*1024}));}}};`); }
if(require.main===module){fs.mkdirSync(path.dirname(destination), { recursive: true });
fs.writeFileSync(destination, '// Generated by server/scripts/build-plugin-chunks.cjs; edit client/common/network/ChunkedPluginMessages.ts.\n' + compile(fs.readFileSync(source,'utf8')));}
module.exports={compile};
