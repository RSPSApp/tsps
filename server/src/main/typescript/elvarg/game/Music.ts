import * as fs from "fs";
import * as path from "path";
import { CacheDefinitions } from "./cache/CacheDefinitions";

type CachedTrack = {
    rowId: number;
    id: number;
    name: string;
    unlockBank?: number;
    unlockBit?: number;
    autoUnlock: boolean;
    parentRowId?: number;
    /** The in-game unlock hint, column 2: "in Varrock.", "during the Dragon Slayer II quest.". */
    unlockHint?: string;
    /** How long the track plays, in game ticks (column 3). */
    lengthTicks?: number;
};

const NO_TRACKS: readonly number[] = [];
const NO_AREA = -1;

/**
 * The Wiki's music areas, tile by tile (`music-areas.json`, generated by
 * `scripts/import-music-areas.mjs`): each area's tracks, and per plane and 64x64 region the area of
 * every tile as "id*count" runs, row by row from the region's south-west corner ("-" is none).
 */
const MUSIC_AREAS: { areas: readonly (readonly number[])[]; tiles: Map<number, Map<number, string>> } = (() => {
    try {
        const data = JSON.parse(fs.readFileSync(path.resolve("data/definitions/music-areas.json"), "utf8"));
        const areas = (data.areas ?? []).map(({ tracks }: { tracks: number[] }) => Object.freeze([...tracks]));
        const tiles = new Map<number, Map<number, string>>();
        for (const [plane, regions] of Object.entries(data.tiles ?? {})) {
            tiles.set(Number(plane), new Map(Object.entries(regions as Record<string, string>).map(([region, runs]) => [Number(region), runs])));
        }
        return { areas, tiles };
    } catch (error) {
        console.warn("[music] failed to load music areas", error);
        return { areas: [], tiles: new Map() };
    }
})();

/** Decoded region grids, by plane << 16 | region: the area of each tile, or NO_AREA. */
const DECODED_GRIDS = new Map<number, Int16Array | null>();

function regionGrid(plane: number, region: number): Int16Array | null {
    const key = (plane << 16) | region;
    let grid = DECODED_GRIDS.get(key);
    if (grid !== undefined) return grid;
    const runs = MUSIC_AREAS.tiles.get(plane)?.get(region);
    grid = null;
    if (runs) {
        grid = new Int16Array(64 * 64).fill(NO_AREA);
        let tile = 0;
        for (const run of runs.split(",")) {
            const [id, count] = run.split("*");
            const length = count === undefined ? 1 : Number(count);
            if (id !== "-") grid.fill(Number(id), tile, tile + length);
            tile += length;
        }
    }
    DECODED_GRIDS.set(key, grid);
    return grid;
}

export class Music {
    /** The silent track. */
    public static readonly SILENCE_TRACK = 147;
    /** Native varp holding the playing track's DB row, -1 between tracks. */
    public static readonly CURRENT_TRACK_VARP = 3883;
    private static tracksCache?: CachedTrack[];
    private static lengthsById?: Map<number, number>;

    private static cachedTracks(): CachedTrack[] {
        if (this.tracksCache) return this.tracksCache;
        const rows = CacheDefinitions.getDbTableRows(44);
        if (rows.length === 0) return [];
        const rowsById = new Map(rows.map((row) => [row.id, row]));
        return this.tracksCache = rows.flatMap((row) => {
            const id = row.int(4, -1);
            const name = row.string(1) || row.string(0);
            if (id < 0 || !name) return [];
            let slot = row.column(5);
            const parentRowId = row.int(12, -1);
            if (slot.length < 2 && parentRowId >= 0) {
                slot = rowsById.get(parentRowId)?.column(5) ?? [];
            }
            const unlockHint = row.string(2);
            const lengthTicks = row.int(3, -1);
            return [{
                rowId: row.id,
                id,
                name,
                ...(slot.length >= 2 ? { unlockBank: Number(slot[0]), unlockBit: Number(slot[1]) } : {}),
                autoUnlock: row.int(6) === 1,
                ...(parentRowId >= 0 ? { parentRowId } : {}),
                ...(unlockHint ? { unlockHint } : {}),
                ...(lengthTicks > 0 ? { lengthTicks } : {}),
            }];
        });
    }

    public static tracks(): CachedTrack[] {
        return this.cachedTracks();
    }

    public static trackNames(): Record<number, string> {
        return Object.fromEntries(this.cachedTracks().map(({ id, name }) => [id, name]));
    }

    /**
     * The tracks of the music area at a tile, the same list for every tile of the area. A floor
     * with no area of its own plays the ground floor's.
     */
    public static tracksAt(x: number, y: number, plane: number): readonly number[] {
        const region = ((x >> 6) << 8) | (y >> 6);
        const tile = ((y & 63) << 6) | (x & 63);
        let area = regionGrid(plane, region)?.[tile] ?? NO_AREA;
        if (area === NO_AREA && plane !== 0) area = regionGrid(0, region)?.[tile] ?? NO_AREA;
        return area === NO_AREA ? NO_TRACKS : MUSIC_AREAS.areas[area] ?? NO_TRACKS;
    }

    /** One of the tracks of the music area at a tile, picked as the area would. */
    public static areaTrackAt(x: number, y: number, plane: number): number | undefined {
        return this.pickAreaTrack(this.tracksAt(x, y, plane));
    }

    /** How many ticks the track plays for, or undefined when the cache has no length. */
    public static lengthTicks(trackId: number): number | undefined {
        if (!this.lengthsById) {
            this.lengthsById = new Map();
            for (const { id, lengthTicks } of this.cachedTracks()) {
                if (lengthTicks !== undefined && !this.lengthsById.has(id)) this.lengthsById.set(id, lengthTicks);
            }
        }
        return this.lengthsById.get(trackId);
    }

    /**
     * A random track of the area. When one has just finished, the next is another of the area's
     * tracks; an area with one track plays it again.
     */
    public static pickAreaTrack(tracks: readonly number[], previous = -1, random: () => number = Math.random): number | undefined {
        const choices = tracks.length > 1 ? tracks.filter((track) => track !== previous) : tracks;
        return choices.length === 0 ? undefined : choices[Math.floor(random() * choices.length) % choices.length];
    }

    /** The cache-map tile an instance tile copies, through its chunk's rotation; undefined outside its chunks. */
    public static instanceSourceTile(area: any, x: number, y: number, plane: number): { x: number; y: number; plane: number } | undefined {
        if (typeof area?.getBaseX !== "function" || typeof area?.getChunk !== "function") return undefined;
        const localX = x - area.getBaseX();
        const localY = y - area.getBaseY();
        const chunk = area.getChunk(plane, localX >> 3, localY >> 3);
        if (!chunk) return undefined;
        // The placed tile turned back: a chunk turned clockwise r times is undone by 4 - r turns.
        const tx = localX & 7;
        const ty = localY & 7;
        const [sx, sy] = [[tx, ty], [7 - ty, tx], [7 - tx, 7 - ty], [ty, 7 - tx]][chunk.rotation & 3];
        return { x: (chunk.sourceChunkX << 3) + sx, y: (chunk.sourceChunkY << 3) + sy, plane: chunk.sourcePlane ?? plane };
    }
}
