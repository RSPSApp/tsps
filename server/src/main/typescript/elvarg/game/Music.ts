import * as fs from "fs";
import * as path from "path";
import { CacheDefinitions } from "./cache/CacheDefinitions";

type CachedTrack = {
    rowId: number;
    id: number;
    name: string;
    unlockBank?: number;
    unlockBit?: number;
    autoUnlock: boolean;
    parentRowId?: number;
    /** The in-game unlock hint, column 2: "in Varrock.", "during the Dragon Slayer II quest.". */
    unlockHint?: string;
    /** How long the track plays, in game ticks (column 3). */
    lengthTicks?: number;
};

const NO_TRACKS: readonly number[] = [];
const NO_AREA = -1;

type MusicAreas = { areas: readonly (readonly number[])[]; tiles: Map<number, Map<number, string>> };

/**
 * The Wiki's music areas, tile by tile (`music-areas.json` for Modern areas and
 * `music-areas-classic.json` for Classic ones, generated by `scripts/import-music-areas.mjs`): each
 * area's tracks, and per plane and 64x64 region the area of every tile as "id*count" runs, row by
 * row from the region's south-west corner ("-" is none).
 */
function loadMusicAreas(file: string): MusicAreas {
    try {
        const data = JSON.parse(fs.readFileSync(path.resolve("data/definitions", file), "utf8"));
        const areas = (data.areas ?? []).map(({ tracks }: { tracks: number[] }) => Object.freeze([...tracks]));
        const tiles = new Map<number, Map<number, string>>();
        for (const [plane, regions] of Object.entries(data.tiles ?? {})) {
            tiles.set(Number(plane), new Map(Object.entries(regions as Record<string, string>).map(([region, runs]) => [Number(region), runs])));
        }
        return { areas, tiles };
    } catch (error) {
        console.warn(`[music] failed to load ${file}`, error);
        return { areas: [], tiles: new Map() };
    }
}

const MODERN_AREAS = loadMusicAreas("music-areas.json");
let classicAreas: MusicAreas | undefined;

/** Decoded region grids, by map, then plane << 16 | region: the area of each tile, or NO_AREA. */
const DECODED_GRIDS = new Map<MusicAreas, Map<number, Int16Array | null>>();

function regionGrid(map: MusicAreas, plane: number, region: number): Int16Array | null {
    let grids = DECODED_GRIDS.get(map);
    if (!grids) DECODED_GRIDS.set(map, grids = new Map());
    const key = (plane << 16) | region;
    let grid = grids.get(key);
    if (grid !== undefined) return grid;
    const runs = map.tiles.get(plane)?.get(region);
    grid = null;
    if (runs) {
        grid = new Int16Array(64 * 64).fill(NO_AREA);
        let tile = 0;
        for (const run of runs.split(",")) {
            const [id, count] = run.split("*");
            const length = count === undefined ? 1 : Number(count);
            if (id !== "-") grid.fill(Number(id), tile, tile + length);
            tile += length;
        }
    }
    grids.set(key, grid);
    return grid;
}

export class Music {
    /** The silent track. */
    public static readonly SILENCE_TRACK = 147;
    /** Native varp holding the playing track's DB row, -1 between tracks. */
    public static readonly CURRENT_TRACK_VARP = 3883;
    /** musicplay: 0 Area, 1 Shuffle, 2 Single. */
    public static readonly MODE_VARP = 18;
    public static readonly AREA_MODE = 0;
    public static readonly SHUFFLE_MODE = 1;
    public static readonly SINGLE_MODE = 2;
    /**
     * musicloop: the music settings the client sets and transmits, as varbits of this varp. The
     * varp's other bits (Music cape flags, the farming tab, the Trawler camera, a fairy ring) are
     * the server's.
     */
    public static readonly SETTINGS_VARP = 19;
    /** music_enableloop: when no other track can play as one ends, it restarts. On by default. */
    public static readonly LOOP_BIT = 0;
    /** music_unlock_text_toggle: 1 hides the unlock message. */
    public static readonly HIDE_UNLOCK_MESSAGE_BIT = 9;
    /** music_area_mode, two bits: 0 Modern areas, 1 Classic. */
    public static readonly AREA_TYPE_SHIFT = 10;
    /** use_previous_music_mode_on_login: 0 starts every login in Area mode. */
    public static readonly KEEP_MODE_ON_LOGIN_BIT = 21;
    /** use_shuffle_mode_on_manual_music_selection: playing a track from the list in Area mode switches to Shuffle, not Single. */
    public static readonly SHUFFLE_ON_SELECTION_BIT = 24;
    /**
     * The client-owned varbits of varp 19: the loop, unlock message, area type, playlist (14-17),
     * text shadow, hidden tracks, login mode, default track, playlist update and selection mode.
     */
    public static readonly SETTINGS_MASK = 0x1 | (0x1 << 9) | (0x3 << 10) | (0x7ff << 14);
    public static readonly DEFAULT_SETTINGS = 1 << Music.LOOP_BIT;
    private static tracksCache?: CachedTrack[];
    private static lengthsById?: Map<number, number>;

    private static cachedTracks(): CachedTrack[] {
        if (this.tracksCache) return this.tracksCache;
        const rows = CacheDefinitions.getDbTableRows(44);
        if (rows.length === 0) return [];
        const rowsById = new Map(rows.map((row) => [row.id, row]));
        return this.tracksCache = rows.flatMap((row) => {
            const id = row.int(4, -1);
            const name = row.string(1) || row.string(0);
            if (id < 0 || !name) return [];
            let slot = row.column(5);
            const parentRowId = row.int(12, -1);
            if (slot.length < 2 && parentRowId >= 0) {
                slot = rowsById.get(parentRowId)?.column(5) ?? [];
            }
            const unlockHint = row.string(2);
            const lengthTicks = row.int(3, -1);
            return [{
                rowId: row.id,
                id,
                name,
                ...(slot.length >= 2 ? { unlockBank: Number(slot[0]), unlockBit: Number(slot[1]) } : {}),
                autoUnlock: row.int(6) === 1,
                ...(parentRowId >= 0 ? { parentRowId } : {}),
                ...(unlockHint ? { unlockHint } : {}),
                ...(lengthTicks > 0 ? { lengthTicks } : {}),
            }];
        });
    }

    public static tracks(): CachedTrack[] {
        return this.cachedTracks();
    }

    public static trackNames(): Record<number, string> {
        return Object.fromEntries(this.cachedTracks().map(({ id, name }) => [id, name]));
    }

    /**
     * The tracks of the music area at a tile, the same list for every tile of the area. A floor
     * with no area of its own plays the ground floor's.
     */
    public static tracksAt(x: number, y: number, plane: number, classic = false): readonly number[] {
        const map = classic ? (classicAreas ??= loadMusicAreas("music-areas-classic.json")) : MODERN_AREAS;
        const region = ((x >> 6) << 8) | (y >> 6);
        const tile = ((y & 63) << 6) | (x & 63);
        let area = regionGrid(map, plane, region)?.[tile] ?? NO_AREA;
        if (area === NO_AREA && plane !== 0) area = regionGrid(map, 0, region)?.[tile] ?? NO_AREA;
        return area === NO_AREA ? NO_TRACKS : map.areas[area] ?? NO_TRACKS;
    }

    /** A bit of the player's music settings (varp 19), from their saved audio settings. */
    public static setting(settings: Readonly<Record<number, number>> | undefined, bit: number, bits = 1): number {
        return ((settings?.[Music.SETTINGS_VARP] ?? Music.DEFAULT_SETTINGS) >>> bit) & ((1 << bits) - 1);
    }

    /** Whether the player uses the Classic music areas. */
    public static classic(settings: Readonly<Record<number, number>> | undefined): boolean {
        return Music.setting(settings, Music.AREA_TYPE_SHIFT, 2) === 1;
    }

    /** One of the tracks of the music area at a tile, picked as the area would. */
    public static areaTrackAt(x: number, y: number, plane: number): number | undefined {
        return this.pickAreaTrack(this.tracksAt(x, y, plane));
    }

    /** How many ticks the track plays for, or undefined when the cache has no length. */
    public static lengthTicks(trackId: number): number | undefined {
        if (!this.lengthsById) {
            this.lengthsById = new Map();
            for (const { id, lengthTicks } of this.cachedTracks()) {
                if (lengthTicks !== undefined && !this.lengthsById.has(id)) this.lengthsById.set(id, lengthTicks);
            }
        }
        return this.lengthsById.get(trackId);
    }

    /**
     * A random track of the area. When one has just finished, the next is another of the area's
     * tracks; when there is no other, it plays again only with `replay` (the loop setting).
     */
    public static pickAreaTrack(tracks: readonly number[], previous = -1, random: () => number = Math.random, replay = true): number | undefined {
        const others = tracks.filter((track) => track !== previous);
        const choices = others.length > 0 || !replay ? others : tracks;
        return choices.length === 0 ? undefined : choices[Math.floor(random() * choices.length) % choices.length];
    }

    /** The cache-map tile an instance tile copies, through its chunk's rotation; undefined outside its chunks. */
    public static instanceSourceTile(area: any, x: number, y: number, plane: number): { x: number; y: number; plane: number } | undefined {
        if (typeof area?.getBaseX !== "function" || typeof area?.getChunk !== "function") return undefined;
        const localX = x - area.getBaseX();
        const localY = y - area.getBaseY();
        const chunk = area.getChunk(plane, localX >> 3, localY >> 3);
        if (!chunk) return undefined;
        // The placed tile turned back: a chunk turned clockwise r times is undone by 4 - r turns.
        const tx = localX & 7;
        const ty = localY & 7;
        const [sx, sy] = [[tx, ty], [7 - ty, tx], [7 - tx, 7 - ty], [ty, 7 - tx]][chunk.rotation & 3];
        return { x: (chunk.sourceChunkX << 3) + sx, y: (chunk.sourceChunkY << 3) + sy, plane: chunk.sourcePlane ?? plane };
    }
}
