const assert = require('node:assert/strict');
const { test } = require('node:test');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const chunks = require('../plugins/quests/questhelper/Chunks.QuestHelper');

test('server chunk transport is generated from the same browser protocol', () => {
  const source = fs.readFileSync(path.resolve(__dirname, '../../client/common/network/ChunkedPluginMessages.ts'), 'utf8');
  const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS } }).outputText;
  assert.equal(fs.readFileSync(path.resolve(__dirname, '../plugins/quests/questhelper/Chunks.QuestHelper.js'), 'utf8'), '// Generated by server/scripts/build-plugin-chunks.cjs; edit client/common/network/ChunkedPluginMessages.ts.\n' + compiled);
});

test('large server results survive the real plugin packet byte limit', () => {
  const data = { session: 'player-session', protocol: 1, type: 'result', text: '🌟雪'.repeat(30000) };
  const parts = chunks.encodeChunkedPluginMessage(data);
  const { encodePluginMessage, decodePluginMessagePayload } = require('../dist/net/protocol/ClientProtocol');
  const assembler = new chunks.ChunkedPluginMessageAssembler(data.session);
  let result;
  for (const part of parts.reverse()) {
    const packet = encodePluginMessage('quest-helper', part);
    assert.ok(packet.length < 16384 + 10);
    // Packet framing is checked by encodePluginMessage; transport data is JSON.
    assert.equal(typeof decodePluginMessagePayload, 'function');
    result = assembler.accept(part, 1);
  }
  assert.deepEqual(result, data);
});
